export function translateUiPattern(value) {
  for (const [pattern, translate] of PATTERNS) {
    const match = value.match(pattern);
    if (match) return translate(...match);
  }
  const punctuation = value.match(/^(.+?)([:?])$/);
  if (punctuation && UI_TRANSLATIONS[punctuation[1]]) return `${UI_TRANSLATIONS[punctuation[1]]}${punctuation[2]}`;
  const parenthesized = value.match(/^\((.+)\)$/);
  if (parenthesized && UI_TRANSLATIONS[parenthesized[1]]) return `(${UI_TRANSLATIONS[parenthesized[1]]})`;
  if (value.includes(",")) {
    const tags = value.split(",").map((tag) => tag.trim());
    if (tags.every((tag) => UI_TRANSLATIONS[tag])) return tags.map((tag) => UI_TRANSLATIONS[tag]).join(", ");
  }
  return null;
}
